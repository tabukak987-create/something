from __future__ import annotations

import os
import re
import secrets
import string
from pathlib import Path

_ENV_KEY_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$")


def _generate_jwt_secret() -> str:
    return secrets.token_hex(32)


def _generate_strong_password(length: int = 20) -> str:
    upper = string.ascii_uppercase
    lower = string.ascii_lowercase
    digits = string.digits
    symbols = "!@#$%^&*_-+=?"
    alphabet = upper + lower + digits + symbols
    chars = [
        secrets.choice(upper),
        secrets.choice(lower),
        secrets.choice(digits),
        secrets.choice(symbols),
    ]
    chars.extend(secrets.choice(alphabet) for _ in range(max(length, 12) - len(chars)))
    secrets.SystemRandom().shuffle(chars)
    return "".join(chars)


def _load_env_lines(env_path: Path) -> list[str]:
    if not env_path.exists():
        return []
    return env_path.read_text(encoding="utf-8").splitlines()


def _extract_key(line: str) -> str | None:
    match = _ENV_KEY_RE.match(line)
    return match.group(1).strip() if match else None


def _write_template(template_path: Path) -> None:
    template_path.write_text(
        """# Autogenerated local configuration template.
# Copy values from here into .env only if you want to override the defaults.

JWT_SECRET_KEY=
ADMIN_USERNAME=admin
ADMIN_PASSWORD=

# Optional compatibility aliases used by older tooling
GATEWAY_ADMIN_USERNAME=admin
GATEWAY_ADMIN_PASSWORD=

# Optional local services
GATEWAY_DB_URL=
REDIS_URL=
""",
        encoding="utf-8",
    )


def _render_env(lines: list[str], updates: dict[str, str]) -> str:
    rendered: list[str] = []
    seen: set[str] = set()
    for line in lines:
        key = _extract_key(line)
        if key and key in updates:
            rendered.append(f"{key}={updates[key]}")
            seen.add(key)
        else:
            rendered.append(line)

    if rendered and rendered[-1].strip():
        rendered.append("")

    for key in (
        "JWT_SECRET_KEY",
        "ADMIN_USERNAME",
        "ADMIN_PASSWORD",
        "GATEWAY_ADMIN_USERNAME",
        "GATEWAY_ADMIN_PASSWORD",
    ):
        if key in updates and key not in seen:
            rendered.append(f"{key}={updates[key]}")

    return "\n".join(rendered).rstrip() + "\n"


def bootstrap_local_environment(project_root: Path) -> dict[str, object]:
    """Create or complete the local .env file and export values into os.environ."""
    env_path = project_root / ".env"
    template_path = project_root / ".env.template"

    if not template_path.exists():
        _write_template(template_path)

    lines = _load_env_lines(env_path)
    existing: dict[str, str] = {}
    for line in lines:
        key = _extract_key(line)
        if not key or key in existing:
            continue
        _, value = line.split("=", 1)
        existing[key] = value.strip()

    jwt_secret = existing.get("JWT_SECRET_KEY", "").strip()
    generated_jwt_secret = False
    if not jwt_secret or len(jwt_secret) < 32:
        jwt_secret = _generate_jwt_secret()
        generated_jwt_secret = True

    admin_username = (
        existing.get("ADMIN_USERNAME")
        or existing.get("GATEWAY_ADMIN_USERNAME")
        or "admin"
    ).strip() or "admin"

    admin_password = (
        existing.get("ADMIN_PASSWORD")
        or existing.get("GATEWAY_ADMIN_PASSWORD")
    )
    generated_admin_password = False
    if not admin_password:
        admin_password = _generate_strong_password()
        generated_admin_password = True

    updates = {
        "JWT_SECRET_KEY": jwt_secret,
        "ADMIN_USERNAME": admin_username,
        "ADMIN_PASSWORD": admin_password,
        "GATEWAY_ADMIN_USERNAME": admin_username,
        "GATEWAY_ADMIN_PASSWORD": admin_password,
    }

    env_path.write_text(_render_env(lines, updates), encoding="utf-8")
    for key, value in updates.items():
        os.environ[key] = value

    return {
        "env_path": str(env_path),
        "template_path": str(template_path),
        "generated_jwt_secret": generated_jwt_secret,
        "generated_admin_password": generated_admin_password,
        "admin_username": admin_username,
        "admin_password": admin_password if generated_admin_password else None,
    }
