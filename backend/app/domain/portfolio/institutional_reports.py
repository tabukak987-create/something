    @classmethod
    async def get_report_history(cls, report_type: Optional[str] = None,
                                   limit: int = 50) -> List[dict]:
        """Get historical report generation log."""
        if report_type:
            rows = await fetch_all(
                """SELECT * FROM report_versions
                   WHERE report_type = :rt ORDER BY generated_at DESC LIMIT :lim""",
                {"rt": report_type, "lim": limit},
            )
        else:
            rows = await fetch_all(
                "SELECT * FROM report_versions ORDER BY generated_at DESC LIMIT :lim",
                {"lim": limit},
            )
        return rows

    @staticmethod
    def _get_bucket(years: float) -> str:
        if years <= 1: return "0-1Y"
        elif years <= 3: return "1-3Y"
        elif years <= 5: return "3-5Y"
        elif years <= 7: return "5-7Y"
        elif years <= 10: return "7-10Y"
        else: return "10Y+"

    @staticmethod
    def _get_detailed_bucket(years: float) -> str:
        if years <= 1: return "0-1Y"
        elif years <= 3: return "1-3Y"
        elif years <= 5: return "3-5Y"
        elif years <= 7: return "5-7Y"
        elif years <= 10: return "7-10Y"
        elif years <= 15: return "10-15Y"
        elif years <= 20: return "15-20Y"
        else: return "20Y+"

    @staticmethod
    def _current_quarter() -> str:
        today = date.today()
        q = (today.month - 1) // 3 + 1
        return f"Q{q} FY{today.year}-{str(today.year + 1)[2:]}" if today.month >= 4 else f"Q{q} FY{today.year - 1}-{str(today.year)[2:]}"

    @staticmethod
    def _compute_compliance_score(breach_report: dict) -> float:
        """Compute compliance score (0-100) based on breach history."""
        total = breach_report.get("total_breaches", 0)
        critical = sum(1 for b in breach_report.get("critical_breaches", []))
        open_count = breach_report.get("open_breaches", 0)

        score = 100.0
        score -= min(total * 2, 30)       # Up to -30 for total breaches
        score -= min(critical * 10, 40)   # Up to -40 for critical breaches
        score -= min(open_count * 5, 30)  # Up to -30 for unresolved
        return max(0, round(score, 1))

