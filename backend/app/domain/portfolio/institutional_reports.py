    @classmethod
    async def initialize(cls):
        """Create report version tracking table."""
        try:
            for stmt in REPORT_VERSION_DDL.strip().split(";"):
                stmt = stmt.strip()
                if stmt:
                    await execute_query(stmt + ";")
            log.info("report_service_initialized")
        except Exception as e:
            log.error("report_service_init_failed", error=str(e))

    @classmethod
    async def _get_next_version(cls, report_type: str) -> int:
        """Get next version number for a report type."""
        row = await fetch_one(
            "SELECT MAX(version) AS max_ver FROM report_versions WHERE report_type = :rt",
            {"rt": report_type},
        )
        return (row["max_ver"] or 0) + 1 if row else 1

    @classmethod
    async def _record_version(cls, report_type: str, version: int,
                                user: str, params: Optional[dict] = None,
                                file_path: Optional[str] = None):
        """Record a report generation event."""
        await execute_query(
            """INSERT INTO report_versions
               (report_type, version, generated_at, generated_by, parameters, file_path)
               VALUES (:rt, :ver, :ga, :gb, :params, :fp)""",
            {
                "rt": report_type, "ver": version,
                "ga": utcnow_iso(),
                "gb": user,
                "params": json.dumps(params) if params else None,
                "fp": file_path,
            },
        )

    @classmethod
    async def generate_portfolio_summary(cls, user: dict) -> dict:
        """
        Portfolio Summary Report â€” comprehensive overview of holdings,
        analytics, allocations, risk metrics.
        """
        version = await cls._get_next_version("PORTFOLIO_SUMMARY")

        # Gather data
        holdings = await fetch_all(
            """SELECT p.isin, p.face_value, p.book_value, p.market_value,
                      p.quantity, p.purchase_date, p.coupon_rate AS p_coupon,
                      p.maturity_date AS p_maturity, p.rating AS p_rating,
                      p.sector AS p_sector, p.category,
                      m.clean_price AS price, m.data_source AS source,
                      m.last_updated AS price_updated,
                      m.ytm, m.modified_duration, m.dv01, m.convexity,
                      b.issuer_name, b.coupon_rate, b.maturity_date AS b_maturity,
                      b.credit_rating, b.issuer_type, b.sector AS b_sector
               FROM portfolio_current_positions p
               LEFT JOIN universal_bond_master b ON p.isin = b.isin
               LEFT JOIN unified_market_data m ON p.isin = m.isin
               ORDER BY p.face_value DESC"""
        )

        total_face = sum(float(h.get("face_value", 0)) for h in holdings)
        total_market = 0.0
        weighted_ytm_sum = 0.0
        weighted_duration_sum = 0.0
        for h in holdings:
            face_value = float(h.get("face_value", 0) or 0)
            price = float(h.get("price", 100) or 100)
            market_value = face_value * price / 100
            if not market_value:
                market_value = float(h.get("market_value") or 0)
            total_market += market_value

            ytm = h.get("ytm")
            if ytm is not None:
                weighted_ytm_sum += float(ytm) * market_value

            duration = h.get("modified_duration")
            if duration is not None:
                weighted_duration_sum += float(duration) * market_value

        weighted_ytm = round(weighted_ytm_sum / total_market, 4) if total_market else 0.0
        weighted_modified_duration = round(weighted_duration_sum / total_market, 4) if total_market else 0.0

        # Rating distribution
        rating_dist = {}
        for h in holdings:
            r = h.get("credit_rating") or h.get("p_rating") or "NR"
            fv = float(h.get("face_value", 0))
            rating_dist[r] = rating_dist.get(r, 0) + fv

        # Sector distribution
        sector_dist = {}
        for h in holdings:
            s = h.get("b_sector") or h.get("p_sector") or "OTHER"
            fv = float(h.get("face_value", 0))
            sector_dist[s] = sector_dist.get(s, 0) + fv

        # Maturity profile
        maturity_buckets = {"0-1Y": 0, "1-3Y": 0, "3-5Y": 0, "5-7Y": 0, "7-10Y": 0, "10Y+": 0}
        today = date.today()
        for h in holdings:
            mat = h.get("b_maturity") or h.get("p_maturity") or h.get("maturity_date") or ""
            if mat:
                try:
                    mat_date = datetime.strptime(mat[:10], "%Y-%m-%d").date()
                    years = (mat_date - today).days / 365.25
                    bucket = cls._get_bucket(years)
                    maturity_buckets[bucket] += float(h.get("face_value", 0))
                except Exception:
                    pass

        report = {
            "report_type": "Portfolio Summary Report",
            "version": version,
            "generated_at": utcnow_iso(),
            "generated_by": user.get("username", "system"),
            "brand": cls.BRAND,
            "as_of_date": date.today().isoformat(),
            "summary": {
                "total_holdings": len(holdings),
                "total_face_value": round(total_face, 2),
                "total_market_value": round(total_market, 2),
                "weighted_ytm": weighted_ytm,
                "weighted_modified_duration": weighted_modified_duration,
                "weighted_duration": weighted_modified_duration,
                "avg_modified_duration": weighted_modified_duration,
                "portfolio_ytm": weighted_ytm,
                "portfolio_duration": weighted_modified_duration,
                "unrealized_pnl": round(total_market - total_face, 2),
                "unrealized_pnl_pct": round((total_market - total_face) / total_face * 100, 2) if total_face else 0,
            },
            "rating_distribution": [
                {"rating": k, "face_value": round(v, 2), "pct": round(v / total_face * 100, 1) if total_face else 0}
                for k, v in sorted(rating_dist.items())
            ],
            "sector_distribution": [
                {"sector": k, "face_value": round(v, 2), "pct": round(v / total_face * 100, 1) if total_face else 0}
                for k, v in sorted(sector_dist.items(), key=lambda x: -x[1])
            ],
            "maturity_profile": [
                {"bucket": k, "face_value": round(v, 2), "pct": round(v / total_face * 100, 1) if total_face else 0}
                for k, v in maturity_buckets.items()
            ],
            "holdings": [
                {
                    "isin": h.get("isin"),
                    "issuer": h.get("issuer_name", ""),
                    "coupon": h.get("coupon_rate") or h.get("p_coupon"),
                    "maturity": h.get("b_maturity") or h.get("p_maturity"),
                    "rating": h.get("credit_rating") or h.get("p_rating"),
                    "face_value": float(h.get("face_value", 0)),
                    "market_price": float(h.get("price", 100)) if h.get("price") else None,
                    "price_source": h.get("source"),
                    "price_updated": h.get("price_updated"),
                }
                for h in holdings[:50]
            ],
            "disclaimer": cls.BRAND["disclaimer"],
        }

        # Keep the report headline metrics aligned with the canonical live portfolio view.
        try:
            from app.domain.portfolio.analytics import compute_full_portfolio_analytics

            live_portfolio = await compute_full_portfolio_analytics(portfolio_id="default")
            live_summary = live_portfolio.get("summary") or {}
            summary = report.get("summary", {})
            summary_updates = {
                "total_holdings": live_summary.get("holdings_count", summary.get("total_holdings")),
                "holdings_count": live_summary.get("holdings_count", summary.get("total_holdings")),
                "total_face_value": live_summary.get("total_face_value", summary.get("total_face_value")),
                "total_market_value": live_summary.get("total_market_value", summary.get("total_market_value")),
                "total_invested": live_summary.get("total_invested", summary.get("total_invested")),
                "weighted_ytm": live_summary.get("weighted_ytm", summary.get("weighted_ytm")),
                "weighted_modified_duration": live_summary.get("weighted_modified_duration", summary.get("weighted_modified_duration")),
                "weighted_duration": live_summary.get("weighted_duration", summary.get("weighted_duration")),
                "avg_modified_duration": live_summary.get("weighted_modified_duration", summary.get("avg_modified_duration")),
                "portfolio_ytm": live_summary.get("weighted_ytm", summary.get("portfolio_ytm")),
                "portfolio_duration": live_summary.get("weighted_modified_duration", summary.get("portfolio_duration")),
                "unrealized_pnl": live_summary.get("unrealized_gain", summary.get("unrealized_pnl")),
                "unrealized_pnl_pct": live_summary.get("unrealized_gain_pct", summary.get("unrealized_pnl_pct")),
                "aum_crores": live_summary.get("aum_crores", summary.get("aum_crores")),
                "invested_crores": live_summary.get("invested_crores", summary.get("invested_crores")),
                "face_value_crores": live_summary.get("face_value_crores", summary.get("face_value_crores")),
                "portfolio_rating": live_summary.get("portfolio_rating", summary.get("portfolio_rating")),
                "credit_quality_rating": live_summary.get("credit_quality_rating", summary.get("credit_quality_rating")),
            }
            summary.update({k: v for k, v in summary_updates.items() if v is not None})
            report["summary"] = summary
        except Exception:
            pass

        await cls._record_version("PORTFOLIO_SUMMARY", version, user.get("username", "system"))
        return report

    @classmethod
    async def generate_duration_ladder(cls, user: dict) -> dict:
        """Duration Ladder Report â€” breakdown by duration bands with risk metrics."""
        version = await cls._get_next_version("DURATION_LADDER")

        holdings = await fetch_all(
            """SELECT p.isin, p.face_value, b.issuer_name, b.coupon_rate,
                      b.maturity_date, b.credit_rating, m.clean_price AS price
               FROM portfolio_current_positions p
               LEFT JOIN universal_bond_master b ON p.isin = b.isin
               LEFT JOIN unified_market_data m ON p.isin = m.isin"""
        )

        today = date.today()
        ladder = {}
        band_keys = ["0-1Y", "1-3Y", "3-5Y", "5-7Y", "7-10Y", "10-15Y", "15-20Y", "20Y+"]
        for bk in band_keys:
            ladder[bk] = {"holdings": [], "total_face": 0, "total_market": 0, "count": 0}

        for h in holdings:
            mat = h.get("maturity_date", "")
            if not mat:
                continue
            try:
                mat_date = datetime.strptime(mat[:10], "%Y-%m-%d").date()
                years = max(0, (mat_date - today).days / 365.25)
            except Exception:
                continue

            band = cls._get_detailed_bucket(years)
            fv = float(h.get("face_value", 0))
            price = float(h.get("price", 100)) if h.get("price") else 100
            mv = fv * price / 100

            ladder[band]["holdings"].append({
                "isin": h.get("isin"), "issuer": h.get("issuer_name"),
                "years_to_maturity": round(years, 2),
                "face_value": fv, "market_value": round(mv, 2),
            })
            ladder[band]["total_face"] += fv
            ladder[band]["total_market"] += mv
            ladder[band]["count"] += 1

        total_face = sum(b["total_face"] for b in ladder.values())

        report = {
            "report_type": "Duration Ladder Report",
            "version": version,
            "generated_at": utcnow_iso(),
            "generated_by": user.get("username", "system"),
            "brand": cls.BRAND,
            "as_of_date": date.today().isoformat(),
            "ladder": [
                {
                    "band": k,
                    "count": v["count"],
                    "total_face_value": round(v["total_face"], 2),
                    "total_market_value": round(v["total_market"], 2),
                    "pct_of_portfolio": round(v["total_face"] / total_face * 100, 1) if total_face else 0,
                    "top_holdings": v["holdings"][:5],
                }
                for k, v in ladder.items() if v["count"] > 0
            ],
            "total_face_value": round(total_face, 2),
            "disclaimer": cls.BRAND["disclaimer"],
        }

        await cls._record_version("DURATION_LADDER", version, user.get("username", "system"))
        return report

    @classmethod
    async def generate_rating_distribution(cls, user: dict) -> dict:
        """Rating Distribution Report â€” detailed credit quality analysis."""
        version = await cls._get_next_version("RATING_DISTRIBUTION")

        holdings = await fetch_all(
            """SELECT p.isin, p.face_value, b.issuer_name, b.credit_rating,
                      b.sector, m.clean_price AS price
               FROM portfolio_current_positions p
               LEFT JOIN universal_bond_master b ON p.isin = b.isin
               LEFT JOIN unified_market_data m ON p.isin = m.isin"""
        )

        rating_order = ["SOV", "AAA", "AA+", "AA", "AA-", "A+", "A", "A-",
                        "BBB+", "BBB", "BBB-", "BB+", "BB", "NR"]
        rating_data = {}

        for h in holdings:
            r = h.get("credit_rating", "NR") or "NR"
            fv = float(h.get("face_value", 0))
            if r not in rating_data:
                rating_data[r] = {"face_value": 0, "count": 0, "issuers": set()}
            rating_data[r]["face_value"] += fv
            rating_data[r]["count"] += 1
            rating_data[r]["issuers"].add(h.get("issuer_name", "UNKNOWN"))

        total_face = sum(d["face_value"] for d in rating_data.values())

        # Investment grade vs sub-IG split
        ig_ratings = {"SOV", "AAA", "AA+", "AA", "AA-", "A+", "A", "A-", "BBB+", "BBB", "BBB-"}
        ig_total = sum(d["face_value"] for r, d in rating_data.items() if r in ig_ratings)

        report = {
            "report_type": "Rating Distribution Report",
            "version": version,
            "generated_at": utcnow_iso(),
            "generated_by": user.get("username", "system"),
            "brand": cls.BRAND,
            "as_of_date": date.today().isoformat(),
            "distribution": [
                {
                    "rating": r,
                    "count": rating_data[r]["count"],
                    "face_value": round(rating_data[r]["face_value"], 2),
                    "pct": round(rating_data[r]["face_value"] / total_face * 100, 1) if total_face else 0,
                    "unique_issuers": len(rating_data[r]["issuers"]),
                }
                for r in rating_order if r in rating_data
            ],
            "credit_quality_summary": {
                "investment_grade_pct": round(ig_total / total_face * 100, 1) if total_face else 0,
                "sub_investment_grade_pct": round((total_face - ig_total) / total_face * 100, 1) if total_face else 0,
                "weighted_avg_rating_score": None,  # Computed by portfolio analytics
                "total_unique_issuers": len(set().union(*(d["issuers"] for d in rating_data.values()))),
            },
            "total_face_value": round(total_face, 2),
            "epfo_compliance": {
                "min_rating_met": all(r not in {"BB+", "BB", "BB-", "B+", "B"} for r in rating_data),
                "sovereign_pct": round(rating_data.get("SOV", {}).get("face_value", 0) / total_face * 100, 1) if total_face else 0,
            },
            "disclaimer": cls.BRAND["disclaimer"],
        }

        await cls._record_version("RATING_DISTRIBUTION", version, user.get("username", "system"))
        return report

