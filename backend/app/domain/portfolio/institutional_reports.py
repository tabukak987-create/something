# Report version tracking
REPORT_VERSION_DDL = """
CREATE TABLE IF NOT EXISTS report_versions (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    report_type TEXT NOT NULL,
    version INTEGER NOT NULL DEFAULT 1,
    generated_at TEXT NOT NULL,
    generated_by TEXT NOT NULL,
    parameters TEXT,
    file_path TEXT,
    file_size INTEGER,
    checksum TEXT,
    metadata_json TEXT
);

CREATE INDEX IF NOT EXISTS idx_report_type ON report_versions(report_type);
CREATE INDEX IF NOT EXISTS idx_report_date ON report_versions(generated_at);

CREATE TABLE IF NOT EXISTS quarterly_snapshots (
    quarter TEXT PRIMARY KEY,
    snapshot_date TEXT NOT NULL,
    total_aum REAL,
    portfolio_ytm REAL,
    portfolio_duration REAL,
    total_holdings INTEGER,
    compliance_score REAL,
    open_breaches INTEGER DEFAULT 0,
    total_breaches INTEGER DEFAULT 0,
    rating_upgrades INTEGER DEFAULT 0,
    rating_downgrades INTEGER DEFAULT 0,
    created_at TEXT DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_snapshot_date ON quarterly_snapshots(snapshot_date);
"""


