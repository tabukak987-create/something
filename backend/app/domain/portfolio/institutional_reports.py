    @classmethod
    async def generate_quarterly_trustee_report(cls, user: dict, quarter: Optional[str] = None) -> dict:
        """
        Quarterly Trustee Report â€” comprehensive quarterly review.
        Combines portfolio, compliance, risk, and governance data.
        Enhanced with: QoQ comparison, rating migration, duration shift, NAV reconciliation.
        """
        version = await cls._get_next_version("QUARTERLY_TRUSTEE")

        portfolio = await cls.generate_portfolio_summary(user)
        rating = await cls.generate_rating_distribution(user)
        compliance = await cls.generate_compliance_status(user)

        # Risk metrics
        try:
            risk_snapshot = await fetch_one(
                """SELECT * FROM risk_metrics
                   ORDER BY calc_date DESC LIMIT 1"""
            )
        except Exception:
            risk_snapshot = None

        # â”€â”€ QoQ AUM Comparison â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
        current_aum = portfolio["summary"]["total_market_value"]
        prev_quarter_snapshot = await fetch_one(
            """SELECT total_aum, portfolio_ytm, portfolio_duration, total_holdings,
                      snapshot_date
               FROM quarterly_snapshots
               ORDER BY snapshot_date DESC LIMIT 1"""
        )
        qoq_comparison = {}
        if prev_quarter_snapshot and prev_quarter_snapshot.get("total_aum"):
            prev_aum = prev_quarter_snapshot["total_aum"]
            qoq_comparison = {
                "previous_aum": prev_aum,
                "current_aum": current_aum,
                "aum_change": round(current_aum - prev_aum, 2),
                "aum_change_pct": round((current_aum - prev_aum) / prev_aum * 100, 2) if prev_aum else 0,
                "previous_ytm": prev_quarter_snapshot.get("portfolio_ytm"),
                "previous_duration": prev_quarter_snapshot.get("portfolio_duration"),
                "previous_holdings": prev_quarter_snapshot.get("total_holdings"),
                "snapshot_date": prev_quarter_snapshot.get("snapshot_date"),
            }
        else:
            qoq_comparison = {
                "note": "No previous quarter snapshot available for comparison",
                "current_aum": current_aum,
            }

        # â”€â”€ Rating Migration Tracking â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
        try:
            rating_migrations = await fetch_all(
                """SELECT isin, old_rating, new_rating, change_type, change_date, source
                   FROM rating_change_log
                   WHERE change_date >= date('now', '-90 days')
                   ORDER BY change_date DESC"""
            )
        except Exception:
            rating_migrations = []
        upgrades = [r for r in rating_migrations if r.get("change_type") == "UPGRADE"]
        downgrades = [r for r in rating_migrations if r.get("change_type") == "DOWNGRADE"]
        migration_summary = {
            "total_changes": len(rating_migrations),
            "upgrades": len(upgrades),
            "downgrades": len(downgrades),
            "watchlist_additions": sum(1 for r in rating_migrations if "WATCH" in (r.get("change_type") or "")),
            "details": rating_migrations[:20],  # Top 20 for report
        }

        # â”€â”€ Duration Shift Analysis â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
        current_duration = portfolio["summary"].get("weighted_modified_duration", portfolio["summary"].get("avg_modified_duration", 0))
        duration_shift = {}
        if prev_quarter_snapshot and prev_quarter_snapshot.get("portfolio_duration"):
            prev_dur = prev_quarter_snapshot["portfolio_duration"]
            duration_shift = {
                "previous_duration": prev_dur,
                "current_duration": current_duration,
                "shift_years": round(current_duration - prev_dur, 2),
                "shift_direction": "EXTENDED" if current_duration > prev_dur else "SHORTENED",
                "within_ips_band": abs(current_duration - prev_dur) <= 1.0,  # Â±1Y tolerance
            }
        else:
            duration_shift = {"current_duration": current_duration, "note": "No prior quarter for comparison"}

